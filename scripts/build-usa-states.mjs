// Rebuilds client/src/lib/usStatesData.ts with detailed outlines, keeping names, colours and facts.
// Usage (needs: npm i us-atlas@3 topojson-client topojson-simplify polylabel):
//   node scripts/build-usa-states.mjs client/src/lib/usStatesData.ts client/src/lib/usStatesData.ts
import fs from "fs";
import * as topo from "topojson-client";
import * as simp from "topojson-simplify";
import polylabel from "polylabel";
const src = process.argv[2], out = process.argv[3], minW = +process.argv[4] || 0.05;
const ts = fs.readFileSync(src, "utf8");
const arr = eval(ts.slice(ts.indexOf("US_STATES: USState[] =") + 22).trim().replace(/;\s*$/, ""));
let us = JSON.parse(fs.readFileSync("node_modules/us-atlas/states-albers-10m.json"));
us = simp.simplify(simp.presimplify(us), minW);
const feats = topo.feature(us, us.objects.states).features;
const byName = Object.fromEntries(feats.map(f => [f.properties.name, f]));
const r = n => Math.round(n * 10) / 10;
const ringArea = ring => { let a = 0; for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) a += (ring[j][0] + ring[i][0]) * (ring[j][1] - ring[i][1]); return Math.abs(a / 2); };
// Alaska's Aleutian Islands stretch past the left edge of the atlas frame,
// so measure the real extent and shift everything to fit with a small margin.
let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
for (const f of feats) { const g = f.geometry; const polys = g.type === "Polygon" ? [g.coordinates] : g.coordinates;
  for (const poly of polys) for (const ring of poly) for (const [x, y] of ring) { minX = Math.min(minX, x); maxX = Math.max(maxX, x); minY = Math.min(minY, y); maxY = Math.max(maxY, y); } }
const M = 6, DX = M - minX, DY = M - minY;
const W = Math.ceil(maxX + DX + M), H = Math.ceil(maxY + DY + M);
// (Neighbouring states share point objects, so shift copies, never in place.)
for (const f of feats) { const g = f.geometry; const shift = poly => poly.map(ring => ring.map(([x, y]) => [x + DX, y + DY]));
  g.coordinates = g.type === "Polygon" ? shift(g.coordinates) : g.coordinates.map(shift); }
const outS = arr.map(s => {
  const f = byName[s.name]; if (!f) throw new Error("missing " + s.name);
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  let d = "";
  for (const poly of polys) for (const ring of poly) {
    let prev = "";
    ring.forEach((p, i) => { const pt = r(p[0]) + "," + r(p[1]); if (pt === prev) return; d += (i ? "L" : "M") + pt; prev = pt; });
    d += "Z";
  }
  const big = polys.reduce((a, b) => ringArea(b[0]) > ringArea(a[0]) ? b : a);
  const [cx, cy] = polylabel(big, 0.5);
  return { ...s, path: d, cx: r(cx), cy: r(cy) };
});
let o = `// Auto-generated by scripts/build-usa-states.mjs — do not edit manually
// US Census Bureau cartographic boundaries 1:10m (us-atlas, Albers USA with Alaska and Hawaii inset)

export interface USState {
  id: string;
  name: string;
  abbr: string;
  path: string;
  cx: number;
  cy: number;
  colour: string;
  capital: string;
  region: string;
  pop: number;
  area_km2: number;
}

export const SVG_WIDTH  = ${W};
export const SVG_HEIGHT = ${H};

export const US_STATES: USState[] = ${JSON.stringify(outS, null, 2)};
`;
fs.writeFileSync(out, o);
console.log("states", outS.length, "bytes", o.length, "points", outS.reduce((a, s) => a + s.path.split(/[ML]/).length, 0));
